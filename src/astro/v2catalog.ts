export function applyV2Bodies(bodies: BodyDef[], orbitList: Elements[]): void {
  bodies.push(...stars, ...planets, ...dwarfs, ...moons, ...craft, ...deep, ...nebulae)
  orbitList.push(...orbits)
  for (const b of bodies) {
    if (b.id === 'mercure' || b.id === 'lune') b.flags = [...(b.flags ?? []), 'regolith']
    if (b.id === 'saturne') b.flags = [...(b.flags ?? []), 'hexagon']
    if (b.id === 'venus') b.flags = [...(b.flags ?? []), 'flow']
    if (b.id === 'uranus' && b.axialTilt < 90) b.axialTilt = 97.77
  }
}

