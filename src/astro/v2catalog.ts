const D = Math.PI / 180
const RS = R_SUN
const RE = R_EARTH

function g(mass: number, radius: number): number {
  return (6.6743e-11 * mass) / (radius * radius)
}

function el(id: string, parent: string, a: number, e: number, iDeg: number, OmDeg: number, wDeg: number, MDeg: number): Elements {
  return { id, parent, a, e, i: iDeg * D, Omega: OmDeg * D, w: wDeg * D, M0: MDeg * D }
}

function body(partial: BodyDef): BodyDef {
  return partial
}

