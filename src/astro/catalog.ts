export interface Elements {
  id: string
  parent: string
  a: number
  e: number
  i: number
  Omega: number
  w: number
  M0: number
}

const D = Math.PI / 180

function g(mass: number, radius: number): number {
  return (6.6743e-11 * mass) / (radius * radius)
}

function elFromL(
  id: string,
  parent: string,
  a: number,
  e: number,
  iDeg: number,
  Ldeg: number,
  periDeg: number,
  nodeDeg: number,
): Elements {
  return {
    id,
    parent,
    a,
    e,
    i: iDeg * D,
    Omega: nodeDeg * D,
    w: (periDeg - nodeDeg) * D,
    M0: (Ldeg - periDeg) * D,
  }
}

function el(
  id: string,
  parent: string,
  a: number,
  e: number,
  iDeg: number,
  OmDeg: number,
  wDeg: number,
  MDeg: number,
): Elements {
  return { id, parent, a, e, i: iDeg * D, Omega: OmDeg * D, w: wDeg * D, M0: MDeg * D }
}

